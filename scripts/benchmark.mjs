// Localization benchmark on generated histories with known ground truth.
//   npm run benchmark
// Every revision is real code run by the real constrained runner (no mocked outcomes).
// Each revision gets a unique comment line, so the content-hash cache can't skip work.
// Ground truth = index of the first revision of the failing run that persists to the head.
import { writeFileSync, mkdirSync } from 'node:fs';
import { CHALLENGES } from '../server/challenges.js';
import { hashCode } from '../server/revisions.js';
import { locateRegression } from '../server/regression.js';
import { createRunner } from '../server/runner.js';

const cart = CHALLENGES['cart-total'];
const GOOD = cart.demoSteps[1].code;
const BAD = cart.demoSteps[2].code;
const runner = createRunner({ maxConcurrent: 1 });

// Deterministic PRNG (mulberry32) so the benchmark is reproducible.
let seed = 20261104;
const rand = () => {
  seed |= 0; seed = (seed + 0x6d2b79f5) | 0;
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};
const randInt = (lo, hi) => lo + Math.floor(rand() * (hi - lo + 1));

/** pattern: array of booleans (true = buggy). Revision 0 must be good, last must be buggy. */
function history(pattern) {
  return pattern.map((buggy, i) => {
    const sourceCode = `${buggy ? BAD : GOOD}// edit ${i}\n`;
    return { id: `r${i}`, sequenceNumber: i + 1, sourceCode, contentHash: hashCode(sourceCode), challengeId: cart.id };
  });
}
const truth = (pattern) => {
  let i = pattern.length - 1;
  while (i > 0 && pattern[i - 1]) i--;
  return i;
};

const scenarios = [];
for (const n of [8, 16, 32, 64]) {
  for (let t = 0; t < 5; t++) {
    const k = randInt(1, n - 1);
    scenarios.push({ kind: 'monotonic', n, pattern: Array.from({ length: n }, (_, i) => i >= k) });
  }
  for (let t = 0; t < 3; t++) {
    // A transient failure that gets fixed, then the persisting regression later.
    const j = randInt(1, Math.floor(n / 2) - 2);
    const k = randInt(Math.floor(n / 2), n - 1);
    scenarios.push({ kind: 'non-monotonic', n, pattern: Array.from({ length: n }, (_, i) => (i >= j && i <= j + 1) || i >= k) });
  }
}

const rows = [];
for (const s of scenarios) {
  const revs = history(s.pattern);
  const expected = `r${truth(s.pattern)}`;
  for (const strategy of ['bisect+verify', 'linear']) {
    const started = performance.now();
    const report = await locateRegression(revs, (rev) => runner.runTests(rev.sourceCode, cart), { strategy });
    rows.push({ ...s, strategy, correct: report.firstFailingRevisionId === expected, testsRun: report.testsRun, ms: performance.now() - started, flagged: report.nonMonotonic, tail: s.n - truth(s.pattern) });
  }
  process.stdout.write('.');
}
console.log();

const groups = new Map();
for (const r of rows) {
  const key = `${r.kind}|${r.n}|${r.strategy}`;
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key).push(r);
}
const avg = (xs) => xs.reduce((a, b) => a + b, 0) / xs.length;
const lines = [
  '| history | checkpoints | strategy | trials | correct | avg test runs | avg failing tail | avg latency (ms) | non-monotonic flagged |',
  '|---|---|---|---|---|---|---|---|---|',
];
for (const [key, rs] of groups) {
  const [kind, n, strategy] = key.split('|');
  lines.push(
    `| ${kind} | ${n} | ${strategy} | ${rs.length} | ${rs.filter((r) => r.correct).length}/${rs.length} | ${avg(rs.map((r) => r.testsRun)).toFixed(1)} | ${avg(rs.map((r) => r.tail)).toFixed(1)} | ${avg(rs.map((r) => r.ms)).toFixed(0)} | ${rs.filter((r) => r.flagged).length}/${rs.length} |`,
  );
}
const total = rows.length;
const correct = rows.filter((r) => r.correct).length;
const table = lines.join('\n');
console.log(table);
console.log(`\nOverall: ${correct}/${total} localizations correct.`);

mkdirSync('docs', { recursive: true });
writeFileSync(
  'docs/BENCHMARK.md',
  `# Regression localization benchmark

Generated by \`npm run benchmark\` (scripts/benchmark.mjs) on ${new Date().toISOString().slice(0, 10)}, Node ${process.version}, ${process.platform}.

## Method
- Challenge: \`cart-total\` (5 predefined tests). Good revisions use the working reducer; bad revisions drop \`* item.quantity\`.
- Each revision appends a unique comment (\`// edit i\`), so every checkpoint is a distinct test execution (no cache hits).
- **Monotonic** histories: good up to a random index k, bad from k to the head.
- **Non-monotonic** histories: a transient 2-revision failure that is fixed, then a persisting regression later.
- Ground truth: the first revision of the failing run that persists to the head.
- Every test run is a real child process through the constrained runner (sequential, \`maxConcurrent: 1\`). Seeded PRNG (mulberry32, seed 20261104), so it's reproducible.
- "Failing tail" = number of checkpoints from the true first failure to the head (inclusive). The verification scan costs about this many runs.

## Results
${table}

Overall: ${correct}/${total} localizations correct.

## Reading this honestly
- These are synthetic histories on one challenge. They show the algorithm and runner behave as designed. They are not evidence about real-world bug populations.
- Bisect+verify saves runs only when the failing tail is short relative to the history: bisection costs about log2(n), but the backward verification scan costs about one run per failing checkpoint. With a long failing tail it costs about as much as a linear scan.
- **The non-monotonic flag is only as good as what was tested.** Bisect+verify located the persisting regression correctly in every non-monotonic history, but flagged none of them: it never tests the earlier transient failure, so it can't see it. The linear scan tests everything and flags the flip whenever one exists (an unflagged short history can be one where the "transient" failure ran straight into the real regression, which is effectively monotonic). So no flag under bisect+verify does not prove monotonic history. Use the full scan when that matters.
- Latency is dominated by Node process start-up for each test run (tens of ms each on this machine).
`,
);
console.log('Wrote docs/BENCHMARK.md');
